import assert from 'node:assert/strict';
import {readFile,writeFile,mkdir,copyFile} from 'node:fs/promises';
import {resolve} from 'node:path';
import {sidebarHost} from './sidebar-check-host.mjs';

const output=resolve('bin/brand-review');
await mkdir(output,{recursive:true});
const host=await sidebarHost('src/Browser.App/bin/x64/Release/net10.0-windows10.0.19041.0/win-x64/Sol.exe');
const settingsFile=resolve(host.profile,'settings.json');
const saved=async()=>{try{return JSON.parse(await readFile(settingsFile,'utf8'));}catch(error){if(error.code==='ENOENT')return {};throw error;}};
const settings=JSON.parse(await readFile(settingsFile,'utf8'));
await writeFile(settingsFile,JSON.stringify({...settings,Onboarded:false,ProfileName:'',Language:'fr',StartWallpaper:true,HomePage:'https://start.sol/index.html#start',Shortcuts:[],AutoPip:true}));
const sessionFile=resolve(host.profile,'session.json');
const session=JSON.parse(await readFile(sessionFile,'utf8'));
session.Groups=session.Groups.map((group,i)=>({...group,Color:i?'#b0b0b0':'#777777'}));
await writeFile(sessionFile,JSON.stringify(session));
const save=async(page,name)=>{
  await host.wait(()=>page.evaluate('[...document.querySelectorAll(".welcome-step > *")].every(e=>Number(getComputedStyle(e).opacity)>.99)'),'visible staged content');
  await writeFile(resolve(output,name),Buffer.from((await page.call('Page.captureScreenshot',{format:'png'})).data,'base64'));
};
try {
  const ui=await host.launch(820,1320);
  const command=c=>ui.evaluate(`chrome.webview.postMessage(${JSON.stringify(JSON.stringify(c))})`);
  const welcome=await host.connect('#welcome');
  await host.wait(()=>welcome.evaluate('!!document.querySelector(".welcome-next")'),'native first setup');
  await host.wait(()=>welcome.evaluate('[...document.images].every(i=>i.complete&&i.naturalWidth>0)'),'new logo loaded');
  assert.equal(await welcome.evaluate('document.querySelectorAll(".preview-shot,canvas").length'),0);
  await save(welcome,'01-configuration.png');
  await welcome.evaluate('document.querySelector("input").focus()');
  await welcome.call('Input.insertText',{text:'Camille'});
  const next=()=>welcome.evaluate('document.querySelector(".welcome-next").click()');
  await next();
  await host.wait(async()=>(await saved()).ProfileName==='Camille','name persisted');
  await save(welcome,'02-import.png');
  await next();
  await host.wait(()=>welcome.evaluate('!!document.querySelector("[aria-label=Thème]")'),'appearance');
  await welcome.evaluate(`document.querySelector('[role=tab][aria-label=Sombre]').click()`);
  await host.wait(async()=>(await saved()).Theme==='dark','theme persisted');
  assert.equal(await welcome.evaluate('getComputedStyle(document.querySelector(".welcome")).backgroundColor'),'rgb(247, 247, 244)');
  await save(welcome,'03-apparence.png');
  await welcome.evaluate('document.querySelector(".welcome-font-more").click()');
  assert.equal(await welcome.evaluate('document.querySelectorAll(".welcome-font-options [role=radio]").length'),14);
  await welcome.evaluate('[...document.querySelectorAll(".welcome-font-options [role=radio]")].at(-1).click()');
  await host.wait(async()=>(await saved()).Font==='lora','font choice persisted');
  await save(welcome,'10-polices.png');
  await welcome.evaluate('[...document.querySelectorAll(".welcome-font-options [role=radio]")].at(-1).focus()');
  await welcome.call('Input.dispatchKeyEvent',{type:'keyDown',key:'Home',code:'Home'});
  await host.wait(async()=>(await saved()).Font==='default','keyboard font choice');
  await welcome.call('Emulation.setDeviceMetricsOverride',{width:420,height:760,deviceScaleFactor:1,mobile:false});
  assert(await welcome.evaluate('document.documentElement.scrollWidth<=innerWidth+1'),'font cards fit 420px');
  await save(welcome,'11-polices-etroit.png');
  await welcome.call('Emulation.clearDeviceMetricsOverride');
  await next();
  await host.wait(()=>welcome.evaluate('!!document.querySelector(".welcome-toggle")'),'settings');
  await welcome.evaluate('document.querySelector(".welcome-toggle [role=switch]").click()');
  await host.wait(async()=>(await saved()).AutoPip===false,'player preference persisted');
  await save(welcome,'04-reglages.png');
  await next();
  await host.wait(()=>welcome.evaluate('!!document.querySelector(".welcome-ready-mark")'),'ready');
  await save(welcome,'05-termine.png');
  await next();
  await host.wait(async()=>(await saved()).Onboarded,'setup completion persisted');
  await command({type:'welcome.open'});
  await host.wait(()=>welcome.evaluate('document.querySelector(".welcome-step-count")?.textContent.includes("IMPORTATION")'),'reopen import without first-run');
  await welcome.call('Emulation.setDeviceMetricsOverride',{width:420,height:760,deviceScaleFactor:1,mobile:false});
  assert(await welcome.evaluate('document.documentElement.scrollWidth<=innerWidth+1'),'narrow setup fits');
  await save(welcome,'06-import-etroit.png');
  await next();
  await command({type:'tab.open',url:'https://start.sol/index.html#start'});
  const start=await host.connect('https://start.sol/index.html#start');
  await host.wait(()=>start.evaluate('document.querySelector(".start-brand")&&document.documentElement.dataset.wallpaper==="true"'),'new default wallpaper');
  await host.wait(()=>start.evaluate('[...document.images].every(i=>i.complete)'),'start image loaded');
  assert(await start.evaluate('getComputedStyle(document.body).backgroundImage.includes("start-background")'));
  await save(start,'07-accueil.png');
  await copyFile(resolve(output,'01-configuration.png'),resolve('docs/images/setup.png'));
  await copyFile(resolve(output,'07-accueil.png'),resolve('docs/images/start.png'));
  await writeFile(resolve(output,'verification.json'),JSON.stringify({nativeWebView2:true,steps:5,nameSaved:true,themeSaved:true,fontSaved:true,fontKeyboard:true,fontChoices:14,playerSaved:true,completionSaved:true,reopenImport:true,narrowWidth:420,screenshotsRemoved:true,newWallpaper:true,realImportExecuted:false},null,2));
  await host.close(ui);
  console.log(`PASS branding + first-run, native preferences and completion, import reopening, 420px layout. Captures: ${output}`);
} finally {await host.dispose();}
